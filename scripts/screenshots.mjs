// Erstellt Dokumentations-Screenshots mit generierten Testmedien.
// Aufruf (Linux): xvfb-run -a node scripts/screenshots.mjs <medienordner> docs/screenshots
import { _electron as electron } from '@playwright/test'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
const [media, shots] = process.argv.slice(2)
fs.mkdirSync(shots, { recursive: true })
const ud = fs.mkdtempSync(path.join(os.tmpdir(), 'ppm-shots-'))
const out = fs.mkdtempSync(path.join(os.tmpdir(), 'ppm-shots-out-'))
const app = await electron.launch({ args: ['--no-sandbox', '.'], env: { ...process.env, PPM_USER_DATA: ud } })
const page = await app.firstWindow()
await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 900))
await page.waitForTimeout(1200)
const stub = (d) => app.evaluate(({ dialog }, x) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [x] }) }, d)
await page.getByRole('button', { name: 'Neues Projekt' }).first().click()
await page.getByLabel('Projektname').fill('Hochzeit 2026')
await page.getByRole('button', { name: 'Projekt anlegen' }).click()
await stub(media)
await page.getByRole('button', { name: 'Quellordner hinzufügen' }).first().click()
for (const [n, c] of [['Anna', null], ['Max', null], ['Familie', null]]) {
  await page.getByRole('button', { name: 'Neues Paket erstellen' }).click()
  await page.getByLabel(/Name des Pakets/).fill(n)
  await page.getByRole('button', { name: 'Paket erstellen', exact: true }).click()
}
await stub(out)
await page.getByRole('button', { name: 'Ausgabeordner wählen' }).click()
await page.waitForTimeout(6000)
const tile = (n) => page.locator('.tile', { has: page.locator('.tile-name', { hasText: n }) }).first()
for (const [f, k] of [['IMG_0002.jpg', '1'], ['IMG_0003.jpg', '1'], ['IMG_0003.jpg', '2'], ['IMG_0005.jpg', '3'], ['IMG_0006.jpg', '1']]) {
  await (await tile(f)).click()
  await page.keyboard.press(k)
}
await (await tile('IMG_0002.jpg')).click()
await (await tile('IMG_0004.jpg')).click({ modifiers: ['Shift'] })
await page.waitForTimeout(800)
await page.screenshot({ path: path.join(shots, 'raster-hell.png') })
await page.locator('#filter-button').click()
await page.getByRole('dialog', { name: 'Medien filtern' }).getByRole('button', { name: 'RAW' }).click()
await page.getByRole('dialog', { name: 'Medien filtern' }).getByRole('button', { name: 'Bild' }).click()
await page.waitForTimeout(400)
await page.screenshot({ path: path.join(shots, 'filter-popover.png') })
await page.keyboard.press('Escape')
await page.getByRole('button', { name: 'Alle Filter zurücksetzen' }).click()
await page.getByRole('button', { name: /^Farbschema/ }).click()
await page.getByRole('button', { name: /^Farbschema/ }).click()
await (await tile('IMG_0003.jpg')).click()
await page.waitForTimeout(500)
await page.screenshot({ path: path.join(shots, 'raster-dunkel.png') })
await page.keyboard.press('Enter')
await page.waitForTimeout(1200)
await page.screenshot({ path: path.join(shots, 'fokusansicht.png') })
await page.keyboard.press('Escape')
await page.getByRole('button', { name: /Exportvorschau öffnen/ }).click()
await page.waitForTimeout(1200)
await page.screenshot({ path: path.join(shots, 'exportvorschau.png') })
await page.keyboard.press('Escape')
await app.close()
fs.rmSync(ud, { recursive: true, force: true })
fs.rmSync(out, { recursive: true, force: true })
console.log('Screenshots gespeichert in', shots)
